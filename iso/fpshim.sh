#!/bin/bash
# Build-time "shim" prefix: upstream headers (matching the host's library versions) plus
# pkg-config files that point at the host's runtime libraries. This lets Flatpak, OSTree and
# bubblewrap be compiled here without the distribution -dev packages; the libraries they link
# against are the same ones copied into the Rudolf OS root file system. GPL-2.0-or-later.
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
H=$HERE/src/fp/hdr
P=$HERE/src/fp/shim
L=/usr/lib/x86_64-linux-gnu
rm -rf "$P"; mkdir -p "$P/include" "$P/lib/pkgconfig"
pc(){ # name version libs-name host-so [cflags-subdir] [requires]
	local inc='${prefix}/include'; [ -n "$5" ] && inc="\${prefix}/include/$5"
	local libs=''; [ -n "$3" ] && { ln -sf "$L/$4" "$P/lib/lib$3.so"; libs="-L\${prefix}/lib -l$3"; }
	cat > "$P/lib/pkgconfig/$1.pc" <<E
prefix=$P
Name: $1
Description: shim for $1
Version: $2
Requires: $6
Libs: $libs
Cflags: -I$inc
E
}
sub(){ sed -e "$2" "$1"; }
# curl 8.5.0
cp -r "$H/curl/include/curl" "$P/include/"; pc libcurl 8.5.0 curl libcurl.so.4
# libarchive 3.7.2
cp "$H/libarchive/libarchive/archive.h" "$H/libarchive/libarchive/archive_entry.h" "$P/include/"; pc libarchive 3.7.2 archive libarchive.so.13
# libxml2 2.9.14
mkdir -p "$P/include/libxml2"; cp -r "$H/libxml2/include/libxml" "$P/include/libxml2/"
sed -e 's/@VERSION@/2.9.14/;s/@LIBXML_VERSION_NUMBER@/20914/;s/@LIBXML_VERSION_EXTRA@//;s/@MODULE_EXTENSION@/.so/' \
    -e 's/@WITH_\(TRIO\|THREAD_ALLOC\|MEM_DEBUG\|RUN_DEBUG\|ICU\|LEGACY\|FTP\)@/0/g;s/@WITH_[A-Z0-9_]*@/1/g' \
    "$H/libxml2/include/libxml/xmlversion.h.in" > "$P/include/libxml2/libxml/xmlversion.h"
pc libxml-2.0 2.9.14 xml2 libxml2.so.2 libxml2
# zstd 1.5.5
cp "$H/zstd/lib/"z*.h "$P/include/"; pc libzstd 1.5.5 zstd libzstd.so.1
# json-glib 1.8.0
mkdir -p "$P/include/json-glib-1.0/json-glib"; J=$P/include/json-glib-1.0/json-glib
cp "$H/json-glib/json-glib/"*.h "$J/"
sed -e 's/@JSON_MAJOR_VERSION@/1/;s/@JSON_MINOR_VERSION@/8/;s/@JSON_MICRO_VERSION@/0/;s/@JSON_VERSION@/1.8.0/' "$H/json-glib/json-glib/json-version.h.in" > "$J/json-version.h"
(cd "$H/json-glib/json-glib" && glib-mkenums --template json-enum-types.h.in json-types.h json-parser.h json-reader.h json-path.h > "$J/json-enum-types.h")
pc json-glib-1.0 1.8.0 json-glib-1.0 libjson-glib-1.0.so.0 json-glib-1.0 "glib-2.0 gobject-2.0 gio-2.0"
# appstream 1.0.2
mkdir -p "$P/include/appstream"; A=$P/include/appstream
cp "$H/appstream/src/"*.h "$A/"
sed -e 's/@AS_MAJOR_VERSION_CONF@/1/;s/@AS_MINOR_VERSION_CONF@/0/;s/@AS_MICRO_VERSION_CONF@/2/;s/@AS_MAJOR_VERSION_PRJ@/1/;s/@AS_MINOR_VERSION_PRJ@/0/;s/@AS_MICRO_VERSION_PRJ@/2/' "$H/appstream/src/as-version.h.in" > "$A/as-version.h"
(cd "$H/appstream/src" && glib-mkenums --identifier-prefix As --symbol-prefix as \
   --fhead '#pragma once\n#include <glib-object.h>\nG_BEGIN_DECLS\n' --ftail 'G_END_DECLS\n' \
   --eprod 'GType @enum_name@_get_type (void) G_GNUC_CONST;\n#define AS_TYPE_@ENUMSHORT@ (@enum_name@_get_type ())\n' \
   $(grep -l "^typedef enum" as-*.h | grep -v private) > "$A/as-enum-types.h")
pc appstream 1.0.2 appstream libappstream.so.5 appstream "glib-2.0 gobject-2.0 gio-2.0"
# gdk-pixbuf 2.42.10
mkdir -p "$P/include/gdk-pixbuf-2.0/gdk-pixbuf"; G=$P/include/gdk-pixbuf-2.0/gdk-pixbuf
cp "$H/gdk-pixbuf/gdk-pixbuf/"*.h "$G/"
sed -e 's/@GDK_PIXBUF_MAJOR@/2/;s/@GDK_PIXBUF_MINOR@/42/;s/@GDK_PIXBUF_MICRO@/10/;s/@GDK_PIXBUF_VERSION@/2.42.10/;s/@GDK_PIXBUF_API_VERSION@/2.0/;s/@GDK_PIXBUF_BINARY_VERSION@/2.10.0/' "$H/gdk-pixbuf/gdk-pixbuf/gdk-pixbuf-features.h.in" > "$G/gdk-pixbuf-features.h"
(cd "$H/gdk-pixbuf/gdk-pixbuf" && glib-mkenums --identifier-prefix Gdk --symbol-prefix gdk \
   --fhead '#pragma once\n#include <glib-object.h>\n#include <gdk-pixbuf/gdk-pixbuf-macros.h>\nG_BEGIN_DECLS\n' --ftail 'G_END_DECLS\n' \
   --eprod 'GDK_PIXBUF_AVAILABLE_IN_ALL GType @enum_name@_get_type (void) G_GNUC_CONST;\n#define GDK_TYPE_@ENUMSHORT@ (@enum_name@_get_type ())\n' \
   gdk-pixbuf-core.h gdk-pixbuf-transform.h > "$G/gdk-pixbuf-enum-types.h")
pc gdk-pixbuf-2.0 2.42.10 gdk_pixbuf-2.0 libgdk_pixbuf-2.0.so.0 gdk-pixbuf-2.0 "glib-2.0 gobject-2.0 gio-2.0"
# libgpg-error 1.47 (header generated by its own mkheader program)
GE=$H/gpg-error/src; T=$(mktemp -d)
gcc -O0 -I"$GE" -o "$T/mkheader" "$GE/mkheader.c"
printf '#define HAVE_SYS_TYPES_H 1\n#define HAVE_STDINT_H 1\n#define HAVE_INTTYPES_H 1\n#define HAVE_SYS_SELECT_H 1\n#define HAVE_SYS_TIME_H 1\n#define HAVE_SIGNAL_H 1\n#define USE_POSIX_THREADS 1\n#define SIZEOF_PTHREAD_MUTEX_T 40\n#define REPLACEMENT_FOR_OFF_T "long"\n' > "$T/config.h"
(cd "$T" && cp -r "$GE"/* . && awk -f mkstrtable.awk -v textidx=3 -v nogettext=1 -v namespace=errsource_ err-sources.h.in > err-sources.h && awk -f mkstrtable.awk -v textidx=3 -v nogettext=1 -v namespace=errcode_ err-codes.h.in > err-codes.h && cp syscfg/lock-obj-pub.x86_64-unknown-linux-gnu.h lock-obj-pub.native.h && ./mkheader --cross x86_64-unknown-linux-gnu gpg-error.h.in config.h 1.47 0x012f00 > "$P/include/gpg-error.h")
cp "$P/include/gpg-error.h" "$P/include/gpgrt.h"; rm -rf "$T"
pc gpg-error 1.47 gpg-error libgpg-error.so.0
# gpgme 1.18.0
sed -e 's/@GPGME_CONFIG_HOST@/x86_64-pc-linux-gnu/;s/@PACKAGE_VERSION@/1.18.0/;s/@VERSION_NUMBER@/0x011200/' \
    -e 's/@INSERT__TYPEDEFS_FOR_GPGME_H@//;s/@NEED__FILE_OFFSET_BITS@/0/g;s/@API__SSIZE_T@/ssize_t/g;s/@API__OFF_T@/off_t/g' \
    "$H/gpgme/src/gpgme.h.in" > "$P/include/gpgme.h"
pc gpgme 1.18.0 gpgme libgpgme.so.11 "" "gpg-error"
# libseccomp 2.5.5
sed -e 's/@VERSION_MAJOR@/2/;s/@VERSION_MINOR@/5/;s/@VERSION_MICRO@/5/' "$H/seccomp/include/seccomp.h.in" > "$P/include/seccomp.h"
cp "$H/seccomp/include/seccomp-syscalls.h" "$P/include/"; pc libseccomp 2.5.5 seccomp libseccomp.so.2
# fuse 3.14.0
mkdir -p "$P/include/fuse3"; cp "$H/fuse/include/"*.h "$P/include/fuse3/"
printf '#define FUSE_HOTFIX_VERSION 0\n#define FUSE_USE_VERSION_DEFAULT 31\n#define HAVE_UTIMENSAT 1\n' > "$P/include/fuse3/libfuse_config.h"
pc fuse3 3.14.0 fuse3 libfuse3.so.3 fuse3
# e2p (header only)
mkdir -p "$P/include/e2p" "$P/include/ext2fs"; cp "$H/e2fs/lib/e2p/"*.h "$P/include/e2p/"; cp "$H/e2fs/lib/ext2fs/ext2_fs.h" "$P/include/ext2fs/"
printf '#pragma once\n#include <linux/types.h>\n' > "$P/include/ext2fs/ext2_types.h"
pc e2p 1.47.0 "" ""
# libcap 2.66: kernel capability ABI + the two calls bubblewrap and flatpak use
mkdir -p "$P/include/sys"
cat > "$P/include/sys/capability.h" <<'E'
#pragma once
#include <sys/types.h>
#include <stdint.h>
#include <linux/capability.h>
extern int capget(cap_user_header_t header, cap_user_data_t data);
extern int capset(cap_user_header_t header, const cap_user_data_t data);
typedef int cap_value_t;
extern int cap_from_name(const char *name, cap_value_t *val);
E
pc libcap 2.66 cap libcap.so.2
echo "shim prefix ready: $P"
