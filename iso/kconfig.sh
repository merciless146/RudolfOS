#!/bin/sh
# Rudolf OS kernel configuration on top of x86_64_defconfig
set -e
cd "$1"
make x86_64_defconfig >/dev/null
C=scripts/config
y(){ for o in "$@"; do $C --enable $o; done; }
n(){ for o in "$@"; do $C --disable $o; done; }
m(){ for o in "$@"; do $C --module $o; done; }
mk(){ for o in "$@"; do $C --keep-case --module $o; done; }
$C --set-str LOCALVERSION "-rudolf"
$C --set-str DEFAULT_HOSTNAME "rudolf"
y MODULES MODULE_COMPRESS_NONE USER_NS
# system updates: the disc's kernel hands over to an updated kernel in a slot on RUDOLFDATA
y KEXEC KEXEC_FILE
# boot, firmware interfaces, framebuffer
y EFI EFI_STUB EFI_MIXED EFI_PARTITION MSDOS_PARTITION BLK_DEV_INITRD RD_XZ RD_GZIP
y CMDLINE_BOOL
$C --set-str CMDLINE "quiet loglevel=3 consoleblank=0 vt.global_cursor_default=0"
$C --set-str INITRAMFS_SOURCE "$2"
y INITRAMFS_COMPRESSION_XZ KERNEL_XZ
y SYSFB_SIMPLEFB DRM DRM_SIMPLEDRM DRM_FBDEV_EMULATION FB FRAMEBUFFER_CONSOLE FB_VESA FB_EFI DRM_PANEL_ORIENTATION_QUIRKS FIRMWARE_EDID
n LOGO
# Intel CPU idle states (battery life on Intel N100 and similar)
y INTEL_IDLE
# CPU speed follows load on every CPU-frequency driver (the userspace governor never changes it)
n CPU_FREQ_DEFAULT_GOV_USERSPACE
y CPU_FREQ_DEFAULT_GOV_SCHEDUTIL
# GPU drivers (modules, loaded by modalias at start-up) for hardware-accelerated graphics
m DRM_I915 DRM_XE DRM_AMDGPU DRM_RADEON DRM_NOUVEAU DRM_BOCHS DRM_QXL DRM_VMWGFX DRM_GMA500 DRM_AST DRM_MGAG200
y DRM_AMDGPU_SI DRM_AMDGPU_CIK DRM_AMD_DC DRM_NOUVEAU_SVM
# filesystems
y SQUASHFS SQUASHFS_XZ SQUASHFS_ZLIB SQUASHFS_FILE_DIRECT ISO9660_FS JOLIET ZISOFS OVERLAY_FS EXT4_FS VFAT_FS MSDOS_FS EXFAT_FS NTFS3_FS TMPFS DEVTMPFS DEVTMPFS_MOUNT NLS_CODEPAGE_437 NLS_ISO8859_1 NLS_UTF8 FAT_DEFAULT_UTF8 UDF_FS
# storage
y BLK_DEV_LOOP BLK_DEV_SR CDROM ATA SATA_AHCI ATA_PIIX ATA_GENERIC PATA_AMD PATA_OLDPIIX BLK_DEV_NVME SCSI BLK_DEV_SD USB_STORAGE USB_UAS MMC MMC_BLOCK MMC_SDHCI MMC_SDHCI_PCI MMC_SDHCI_ACPI MMC_REALTEK_PCI MISC_RTSX_PCI VIRTIO VIRTIO_PCI VIRTIO_BLK SCSI_VIRTIO VIRTIO_NET VIRTIO_INPUT
# USB and input
y USB USB_PCI USB_XHCI_HCD USB_XHCI_PCI USB_EHCI_HCD USB_EHCI_PCI USB_OHCI_HCD USB_OHCI_HCD_PCI USB_UHCI_HCD HID HID_GENERIC USB_HID HID_MULTITOUCH HID_APPLE HID_LOGITECH HID_LOGITECH_DJ HID_LOGITECH_HIDPP HID_MICROSOFT I2C_HID_ACPI I2C_DESIGNWARE_CORE I2C_DESIGNWARE_PLATFORM I2C_DESIGNWARE_PCI INPUT_EVDEV INPUT_MOUSEDEV KEYBOARD_ATKBD MOUSE_PS2 SERIO_I8042 INPUT_UINPUT HIDRAW USB_HIDDEV INPUT_TOUCHSCREEN INPUT_JOYSTICK JOYSTICK_XPAD HID_SONY HID_NINTENDO HID_PLAYSTATION
y PINCTRL_INTEL PINCTRL_ALDERLAKE PINCTRL_TIGERLAKE PINCTRL_METEORLAKE PINCTRL_CANNONLAKE PINCTRL_SUNRISEPOINT PINCTRL_AMD
# laptop touchpads: Intel LPSS (the I2C controllers most Intel laptops' touchpads sit on), the GPIO controllers
# their interrupts use (PINCTRL and GPIOLIB were off in 1.1, which also disabled the pin controllers above), ELAN and Synaptics (RMI4) touchpads on I2C/SMBus, Elantech on PS/2, Apple trackpads
y PINCTRL GPIOLIB GPIO_ACPI MFD_INTEL_LPSS_PCI MFD_INTEL_LPSS_ACPI INTEL_IDMA64 I2C_DESIGNWARE_BAYTRAIL I2C_PIIX4
y PINCTRL_ICELAKE PINCTRL_JASPERLAKE PINCTRL_ELKHARTLAKE PINCTRL_LAKEFIELD PINCTRL_BROXTON PINCTRL_GEMINILAKE PINCTRL_BAYTRAIL PINCTRL_CHERRYVIEW PINCTRL_LYNXPOINT
y MOUSE_PS2_ELANTECH MOUSE_PS2_ELANTECH_SMBUS MOUSE_ELAN_I2C MOUSE_ELAN_I2C_I2C MOUSE_ELAN_I2C_SMBUS RMI4_CORE RMI4_SMB RMI4_F03 RMI4_F11 RMI4_F12 RMI4_F30
y HID_ALPS HID_ASUS HID_LENOVO HID_ELAN MOUSE_BCM5974 HID_MAGICMOUSE TOUCHSCREEN_ELAN
# sound
y SND_HDA_CODEC_REALTEK SND_HDA_CODEC_HDMI SND_HDA_CODEC_CIRRUS PINCTRL_INTEL_PLATFORM SOUND SND SND_PCI SND_HDA_INTEL SND_HDA_GENERIC SND_HDA_CODEC_REALTEK_LIB SND_HDA_CODEC_ALC269 SND_HDA_CODEC_ALC662 SND_HDA_CODEC_ALC882 SND_HDA_CODEC_ALC680 SND_HDA_CODEC_ALC260 SND_HDA_CODEC_ALC262 SND_HDA_CODEC_ALC268 SND_HDA_CODEC_ALC861 SND_HDA_CODEC_ALC861VD SND_HDA_CODEC_ALC880 SND_HDA_CODEC_ANALOG SND_HDA_CODEC_SIGMATEL SND_HDA_CODEC_VIA SND_HDA_CODEC_CONEXANT SND_HDA_CODEC_CMEDIA SND_HDA_CODEC_CA0132 SND_HDA_CODEC_HDMI_GENERIC SND_HDA_CODEC_HDMI_INTEL SND_HDA_CODEC_HDMI_ATI SND_HDA_CODEC_HDMI_NVIDIA SND_USB SND_USB_AUDIO SND_INTEL8X0 SND_ENS1370 SND_HDA_CODEC_CS420X SND_HDA_CODEC_CS8409
# network
y PACKET UNIX INET IPV6 NETDEVICES ETHERNET E1000 E1000E IGB IGC R8169 ATL1C ALX TIGON3 8139CP 8139TOO NE2K_PCI PCNET32 USB_NET_DRIVERS USB_USBNET USB_NET_CDCETHER USB_RTL8152 USB_NET_AX88179_178A WIREGUARD
m CFG80211 MAC80211 IWLWIFI IWLMVM IWLDVM RTW88 RTW88_8822BE RTW88_8822CE RTW88_8821CE RTW89 RTW89_8852AE RTW89_8852BE RTW89_8852CE RTW89_8852BTE RTW89_8851BE RTW89_8922AE ATH9K ATH10K ATH10K_PCI ATH11K ATH11K_PCI MT7921E MT7922E RTL8192CE RT2800USB RTL8XXXU MAC80211_HWSIM RTW88_USB RTW88_8821CU RTW88_8822BU RTW88_8822CU RTW88_8821AU RTW88_8812AU RTW89_8852BU RTW89_8851BU MT7921U MT7925E MT7925U ATH9K_HTC MT7601U
# options with lower case in their names (scripts/config upper-cases names unless told not to)
mk MT76x0U MT76x2U
y FW_LOADER
# power, ACPI
y ACPI ACPI_BATTERY ACPI_AC ACPI_BUTTON ACPI_VIDEO ACPI_FAN ACPI_THERMAL BACKLIGHT_CLASS_DEVICE SUSPEND CPU_FREQ X86_INTEL_PSTATE X86_AMD_PSTATE RTC_DRV_CMOS HWMON SENSORS_CORETEMP SENSORS_K10TEMP
# Secure Boot (1.2.2): modules are signed at build time with a key made for that build only (and thrown away),
# and unsigned ones are refused; kexec starts only kernels signed with the Rudolf OS Secure Boot key, which is
# built in as a trusted key (SB_CERT: iso/boot/sb/rudolf-sb.crt, or a test certificate for local builds); with
# Secure Boot on the start-up locks the kernel down (integrity, see initramfs/init); dm-verity checks the system layers as they are read;
# efivarfs lets the start-up read the boot menu's choice and the Secure Boot state
y MODULE_SIG MODULE_SIG_FORCE MODULE_SIG_ALL MODULE_SIG_SHA256
$C --set-str MODULE_SIG_HASH sha256
$C --set-str MODULE_SIG_KEY "certs/signing_key.pem"
y SYSTEM_TRUSTED_KEYRING SECONDARY_TRUSTED_KEYRING
$C --set-str SYSTEM_TRUSTED_KEYS "${SB_CERT:?SB_CERT: the Secure Boot certificate (PEM)}"
y KEXEC_SIG KEXEC_BZIMAGE_VERIFY_SIG SIGNED_PE_FILE_VERIFICATION
y SECURITY SECURITYFS SECURITY_LOCKDOWN_LSM SECURITY_LOCKDOWN_LSM_EARLY LOCK_DOWN_KERNEL_FORCE_NONE
$C --set-str LSM "lockdown,landlock,yama"
y MD BLK_DEV_DM DM_VERITY CRYPTO_SHA256 EFIVAR_FS
# processor microcode (1.2.4): AMD's updates built into the kernel, so the start applies them before anything
# else runs (fixes such as SRSO's "IBPB-extending microcode not applied"). UCODE_DIR: a folder holding
# amd-ucode/ (the pinned files of firmware-extra.txt); without it the kernel has none, as before.
y MICROCODE MICROCODE_AMD MICROCODE_INTEL
if [ -n "$UCODE_DIR" ] && [ -d "$UCODE_DIR/amd-ucode" ]; then
	$C --set-str EXTRA_FIRMWARE "$(cd "$UCODE_DIR" && ls amd-ucode/microcode_amd*.bin | tr '\n' ' ' | sed 's/ $//')"
	$C --set-str EXTRA_FIRMWARE_DIR "$UCODE_DIR"
fi
# speed up the build
n DEBUG_INFO DEBUG_INFO_DWARF5 DEBUG_INFO_DWARF4 DEBUG_INFO_DWARF_TOOLCHAIN_DEFAULT DEBUG_INFO_BTF KALLSYMS_ALL FTRACE
$C --enable DEBUG_INFO_NONE
make olddefconfig >/dev/null
