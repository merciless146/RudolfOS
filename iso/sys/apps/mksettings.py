def jsre(src, at):
    """a JS regex literal starting at src[at] == '/': (pattern, flags, end)"""
    i = at + 1; cls = False
    while i < len(src):
        c = src[i]
        if c == '\\': i += 2; continue
        if c == '[': cls = True
        elif c == ']': cls = False
        elif c == '/' and not cls: break
        i += 1
    j = i + 1
    while j < len(src) and src[j].isalpha(): j += 1
    return src[at + 1:i], src[i + 1:j], j
