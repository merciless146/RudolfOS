#!/usr/bin/env python3
"""rudolf-present's generated part (1.6.3, docs/plan-1.6.3.md Part 1: the Office apps native), made at build time from the
web PresentPro itself, so the native window's lists are the page's and never drift from it:

    python3 mkpresentpro.py OUT.h

(run by iso/sys/ui/build.sh when it builds "presentpro", beside mkui.py's header)

  - the fonts (desktop/office45.js's OFF_FONTS), in the page's order;
  - the font sizes (desktop/ppro45.js's own list on the toolbar), in the page's order;
  - the themes (desktop/pprof45.js's PP_THEMES: its name, its background, its two inks, its six accents and its two fonts);
  - the layouts (PP_LAYOUTS: the key a slide holds, and the name the menus and the toolbar show);
  - the shapes (PP_SHAPES: the first four are the Insert menu's own, beside "More shapes…").

Values the page changes are read here, never copied by hand: a list that cannot be found is an error, never a quiet default.
GPL-2.0-or-later."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ISO = os.path.dirname(os.path.dirname(HERE)); TOP = os.path.dirname(ISO)
OFFICE = os.path.join(TOP, 'desktop', 'office45.js')
PPRO = os.path.join(TOP, 'desktop', 'ppro45.js')
PPROF = os.path.join(TOP, 'desktop', 'pprof45.js')
NACC = 6


def die(m):
    sys.stderr.write('mkpresentpro.py: ' + m + '\n')
    sys.exit(1)


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def block(src, name, where):
    """the text of `const NAME=...;`, from the name to the semicolon that ends it"""
    m = re.search(r'const ' + name + r'\s*=', src)
    if not m:
        die('%s: %s was not found' % (where, name))
    i = m.end(); depth = 0
    while i < len(src):
        c = src[i]
        if c in '[{':
            depth += 1
        elif c in ']}':
            depth -= 1
            if depth == 0:
                return src[m.end():i + 1]
        elif c == ';' and depth == 0:
            return src[m.end():i]
        i += 1
    die('%s: %s does not end' % (where, name))


def pairs(text):
    return re.findall(r"\['([^']+)','((?:[^'\\]|\\.)*)'\]", text)


def main(out):
    for f in (OFFICE, PPRO, PPROF):
        if not os.path.isfile(f):
            die('the page (%s) is not here' % f)
    office = open(OFFICE, encoding='utf-8').read()
    ppro = open(PPRO, encoding='utf-8').read()
    pprof = open(PPROF, encoding='utf-8').read()
    m = re.search(r'const OFF_FONTS=\[([^\]]*)\];', office)
    if not m:
        die("office45.js's OFF_FONTS (the fonts) was not found")
    fonts = re.findall(r"'([^']+)'", m.group(1))
    if len(fonts) < 5:
        die('OFF_FONTS has %d fonts: not read' % len(fonts))
    m = re.search(r"title='Font size'>\$\{\[([0-9,\s]+)\]", ppro)
    if not m:
        die("ppro45.js's font sizes (the toolbar's own list) were not found")
    sizes = [int(x) for x in re.sub(r'\s', '', m.group(1)).split(',') if x]
    if len(sizes) < 5:
        die("the toolbar's font sizes are %d: not read" % len(sizes))
    # (a theme is one line of the page's: its name, its background, its two inks, its accents, its two fonts)
    tb = block(pprof, 'PP_THEMES', 'pprof45.js')
    themes = []
    for m in re.finditer(r"([A-Za-z0-9_]+):\{([^}]*)\}", tb):
        key, body = m.group(1), m.group(2)
        f = dict((k, v) for k, v in re.findall(r"(\w+):'((?:[^'\\]|\\.)*)'", body))
        acc = re.search(r'acc:\[([^\]]*)\]', body)
        if not acc:
            die('the theme %s has no accents' % key)
        ac = re.findall(r"'([^']*)'", acc.group(1))
        for need in ('name', 'bg', 'fg', 'title', 'tf', 'bf'):
            if need not in f:
                die('the theme %s has no %s' % (key, need))
        if len(ac) != NACC:
            die('the theme %s has %d accents, not %d' % (key, len(ac), NACC))
        themes.append((key, f, ac))
    if len(themes) < 8:
        die('PP_THEMES has %d themes: not read' % len(themes))
    lays = pairs(block(pprof, 'PP_LAYOUTS', 'pprof45.js'))
    if len(lays) < 8:
        die('PP_LAYOUTS has %d layouts: not read' % len(lays))
    for need in ('title', 'content', 'two', 'compare', 'section', 'titleonly', 'blank', 'picture'):
        if need not in [k for k, _ in lays]:
            die('PP_LAYOUTS has no %s' % need)
    shapes = pairs(block(pprof, 'PP_SHAPES', 'pprof45.js'))
    if len(shapes) < 4:
        die('PP_SHAPES has %d shapes: not read' % len(shapes))
    o = ['/* (generated by iso/sys/apps/mkpresentpro.py at build time from the web PresentPro: never by hand) */']
    o.append('static const char *const PP_FONTS[] = {')
    for f in fonts:
        o.append('\t%s,' % cstr(f))
    o.append('};')
    o.append('#define NPPFONTS %d' % len(fonts))
    o.append('static const int PP_SIZES[] = {')
    o.append('\t' + ', '.join(str(s) for s in sizes))
    o.append('};')
    o.append('#define NPPSIZES %d' % len(sizes))
    o.append('typedef struct { const char *key, *name, *bg, *fg, *title, *acc[%d], *band, *tf, *bf; } PpTheme;' % NACC)
    o.append('static const PpTheme PP_THEMES[] = {')
    for key, f, ac in themes:
        band = f.get('band', '')
        o.append('\t{ %s, %s, %s, %s, %s, { %s }, %s, %s, %s },' % (cstr(key), cstr(f['name']), cstr(f['bg']), cstr(f['fg']),
                                                                   cstr(f['title']), ', '.join(cstr(a) for a in ac),
                                                                   cstr(band), cstr(f['tf']), cstr(f['bf'])))
    o.append('};')
    o.append('#define NPPTHEMES %d' % len(themes))
    o.append('typedef struct { const char *key, *name; } PpLayout;   /* (a slide\'s layout: what a slide holds, and its name) */')
    o.append('static const PpLayout PP_LAYOUTS[] = {')
    for k, n in lays:
        o.append('\t{ %s, %s },' % (cstr(k), cstr(n)))
    o.append('};')
    o.append('#define NPPLAYOUTS %d' % len(lays))
    o.append('typedef struct { const char *key, *name; } PpShape;')
    o.append('static const PpShape PP_SHAPES[] = {')
    for k, n in shapes:
        o.append('\t{ %s, %s },' % (cstr(k), cstr(n)))
    o.append('};')
    o.append('#define NPPSHAPES %d' % len(shapes))
    open(out, 'w', encoding='utf-8').write('\n'.join(o) + '\n')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        die('usage: mkpresentpro.py OUT.h')
    main(sys.argv[1])
