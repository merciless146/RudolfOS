#!/usr/bin/env python3
"""rudolf-sheets's generated part (1.6.3, docs/plan-1.6.3.md Part 1: the Office apps native), made at build time from the
web SpreadsheetPro itself, so the native toolbar's lists are the page's and never drift from it:

    python3 mksheetpro.py OUT.h

(run by iso/sys/ui/build.sh when it builds "sheetpro", beside mkui.py's header)

  - the fonts (desktop/office45.js's OFF_FONTS), in the page's order;
  - the font sizes (desktop/spro45.js's own list on the toolbar), in the page's order;
  - the number formats (desktop/spro45.js's SP_NF: its names and the codes it sets), in the page's order.

Values the page changes are read here, never copied by hand: a list that cannot be found is an error, never a quiet default.
GPL-2.0-or-later."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ISO = os.path.dirname(os.path.dirname(HERE)); TOP = os.path.dirname(ISO)
OFFICE = os.path.join(TOP, 'desktop', 'office45.js')
SPRO = os.path.join(TOP, 'desktop', 'spro45.js')


def die(m):
    sys.stderr.write('mksheetpro.py: ' + m + '\n')
    sys.exit(1)


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main(out):
    for f in (OFFICE, SPRO):
        if not os.path.isfile(f):
            die('the page (%s) is not here' % f)
    office = open(OFFICE, encoding='utf-8').read()
    spro = open(SPRO, encoding='utf-8').read()
    m = re.search(r"const OFF_FONTS=\[([^\]]*)\];", office)
    if not m:
        die("office45.js's OFF_FONTS (the fonts) was not found")
    fonts = re.findall(r"'([^']+)'", m.group(1))
    if len(fonts) < 5:
        die("OFF_FONTS has %d fonts: not read" % len(fonts))
    m = re.search(r"title='Font size'>\$\{\[([0-9,\s]+)\]", spro)
    if not m:
        die("spro45.js's font sizes (the toolbar's own list) were not found")
    sizes = [int(x) for x in re.sub(r'\s', '', m.group(1)).split(',') if x]
    if len(sizes) < 5:
        die("the toolbar's font sizes are %d: not read" % len(sizes))
    m = re.search(r"const SP_NF=(\[\[.*?\]\]);", spro, re.S)
    if not m:
        die("spro45.js's SP_NF (the number formats) was not found")
    nf = re.findall(r"\['([^']*)','([^']*)'\]", m.group(1))
    if len(nf) < 5:
        die("SP_NF has %d formats: not read" % len(nf))
    o = ['/* (generated by iso/sys/apps/mksheetpro.py at build time from the web SpreadsheetPro: never by hand) */']
    o.append('static const char *const SP_FONTS[] = {')
    for f in fonts:
        o.append('\t%s,' % cstr(f))
    o.append('};')
    o.append('#define NSPFONTS %d' % len(fonts))
    o.append('static const int SP_SIZES[] = {')
    o.append('\t' + ', '.join(str(s) for s in sizes))
    o.append('};')
    o.append('#define NSP_SIZES %d' % len(sizes))
    o.append('typedef struct { const char *name, *code; } SpNf;   /* (a number format: its name, and the code it sets) */')
    o.append('static const SpNf SP_NF[] = {')
    for n, c in nf:
        o.append('\t{ %s, %s },' % (cstr(n), cstr(c)))
    o.append('};')
    o.append('#define NSPNF %d' % len(nf))
    open(out, 'w', encoding='utf-8').write('\n'.join(o) + '\n')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        die('usage: mksheetpro.py OUT.h')
    main(sys.argv[1])
