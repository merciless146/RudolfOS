function termHelp(P,a){const k=String((a&&a[0])||'').toUpperCase();
 if(k==='ALL')return P.print(HELP_FULL);
 if(HELP_ONE[k])return P.print(HELP_ONE[k]);
 if(k&&k!=='HELP')return P.print('No help for "'+k+'". Type HELP ALL for the list.');
 P.print(HELP_SHORT)}
